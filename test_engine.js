// Comprehensive Test Suite for Excel Comparison Tool
const fs = require('fs');
const XLSX = require('./src/vendor/xlsx.full.min.js');

// Mock browser window/globalThis environment
global.window = global;
global.XLSX = XLSX;
require('./src/core/normalizer.js');
require('./src/core/comparisonEngine.js');
require('./src/services/excelService.js');

console.log('Testing Excel Comparison Tool Engine & Header Detection...');

// 1. Create File A (Normal layout, header on row 1)
const fileAData = [
  ['EmpID', 'FullName', 'Department', 'Salary', 'Status'],
  ['EMP001', 'Aarav Sharma', 'Engineering', 85000, 'Active'],
  ['EMP002', 'Diya Patel', 'Marketing', 62000, 'Active'],
  ['EMP003', 'Rohan Mehta', 'Sales', 54000, 'Pending'],
  ['EMP004', 'Neha Gupta', 'HR', 48000, 'Active'],
  ['EMP005', 'Vikram Singh', 'Engineering', 92000, 'Active'], // Only in A
  ['EMP006', 'Duplicate User', 'Sales', 40000, 'Active'],
  ['EMP006', 'Duplicate User', 'Sales', 40000, 'Active']   // Duplicate in A
];
const wbA = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(wbA, XLSX.utils.aoa_to_sheet(fileAData), 'Employees');

// 2. Create File B (Tricky layout: Title on row 1, Metadata on row 2, Blank row 3, Headers on row 4!)
const fileBData = [
  ['CONFIDENTIAL - COMPANY PAYROLL AUDIT REPORT - 2024'], // Row 1
  ['Export Date: 2024-11-17', 'Generated by: Audit System'], // Row 2
  [], // Row 3
  ['Employee_Code', 'Employee_Name', 'Dept', 'Monthly_Salary', 'Status_Flag'], // Row 4 (Real Headers!)
  ['EMP001', 'Aarav Sharma', 'Engineering', 85000, 'Active'], // Exact Match
  ['EMP002', 'Diya Patel', 'Marketing', 65000, 'Active'],     // Mismatched Salary (62000 vs 65000)
  ['EMP003', 'Rohan Mehta', 'Sales', 54000, 'Approved'],      // Mismatched Status (Pending vs Approved)
  ['EMP004', 'Neha Gupta', 'HR', 48000, 'Active'],            // Exact Match
  ['EMP007', 'Suresh Kumar', 'Finance', 71000, 'Active'],     // Only in B
  ['EMP006', 'Duplicate User', 'Sales', 40000, 'Active'],
  ['EMP006', 'Duplicate User', 'Sales', 40000, 'Active']      // Duplicate in B
];
const wbB = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(wbB, XLSX.utils.aoa_to_sheet(fileBData), 'PayrollData');

// 3. Test Table Parsing & Header Detection
const tableA = ECT.excel.table(wbA, 'Employees');
console.log('File A Headers detected (row ' + (tableA.headerRow + 1) + '):', tableA.headers);
console.assert(tableA.headers.length === 5, 'File A should have 5 headers');
console.assert(tableA.rows.length === 7, 'File A should have 7 rows');

const tableB = ECT.excel.table(wbB, 'PayrollData');
console.log('File B Headers detected (row ' + (tableB.headerRow + 1) + '):', tableB.headers);
console.assert(tableB.headerRow === 3, 'File B header row should be detected at index 3 (Row 4)');
console.assert(tableB.headers.length === 5, 'File B should have 5 headers');
console.assert(tableB.headers[0] === 'Employee_Code', 'File B header 0 should be Employee_Code');
console.assert(tableB.rows.length === 7, 'File B should have 7 data rows');

// 4. Test Comparison
const cfg = {
  keys: [{ a: 'EmpID', b: 'Employee_Code' }],
  fields: [
    { a: 'FullName', b: 'Employee_Name' },
    { a: 'Department', b: 'Dept' },
    { a: 'Salary', b: 'Monthly_Salary' },
    { a: 'Status', b: 'Status_Flag' }
  ],
  options: { ignoreCase: true, tolerance: 0 }
};

const validationErrors = ECT.engine.validate(tableA, tableB, cfg);
console.log('Validation errors:', validationErrors);
console.assert(validationErrors.length === 0, 'Validation should pass');

const res = ECT.engine.compare(tableA, tableB, cfg);

console.log('\n--- Comparison Results ---');
console.log('Exact Matched count:', res.matched.length, '(Expected: 2 -> EMP001, EMP004)');
console.log('Mismatched count:', res.mismatched.length, '(Expected: 2 -> EMP002, EMP003)');
console.log('Duplicate count:', res.duplicate.length, '(Expected: 1 -> EMP006)');
console.log('Ambiguous count:', res.ambiguous.length, '(Expected: 0)');
console.log('Unmatched File A count:', res.unmatched.filter(u => u.side === 'a').length, '(Expected: 1 -> EMP005)');
console.log('Unmatched File B count:', res.unmatched.filter(u => u.side === 'b').length, '(Expected: 1 -> EMP007)');

console.log('\nIntegrity Audit Status:');
console.log('File A Integrity OK:', res.stats.a.ok, 'Total:', res.stats.a.total, 'Placed:', res.stats.a.placed);
console.log('File B Integrity OK:', res.stats.b.ok, 'Total:', res.stats.b.total, 'Placed:', res.stats.b.placed);

console.assert(res.matched.length === 2, 'Matched count mismatch');
console.assert(res.mismatched.length === 2, 'Mismatched count mismatch');
console.assert(res.duplicate.length === 1, 'Duplicate count mismatch');
console.assert(res.stats.a.ok && res.stats.b.ok, 'Integrity audit must be 100% OK');

console.log('\nAll tests PASSED successfully!');
